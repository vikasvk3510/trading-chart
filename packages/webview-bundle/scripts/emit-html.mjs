import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(resolve(here, '../dist/index.html'), 'utf8');
const escaped = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const nativeDir = resolve(here, '../../native');
writeFileSync(
  resolve(nativeDir, 'src/chartHtml.ts'),
  `/* Generated by tradingcandle-webview. Do not edit. */\nexport const chartHtml: string = \`${escaped}\`;\n`,
);
writeFileSync(resolve(nativeDir, 'chart.html'), html);
console.log(`Wrote inline chart HTML (${html.length} bytes)`);
